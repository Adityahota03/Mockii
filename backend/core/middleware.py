"""
core/middleware.py
──────────────────
Two lightweight WSGI middlewares for Mockii:

RequestIDMiddleware
    Attaches a unique request ID to every request object.
    Honours an incoming X-Request-ID header so external callers (tests,
    load-balancers, client support tools) can correlate log entries with a
    specific request they generated.
    Echoes the ID back in the X-Request-ID response header.

APILoggingMiddleware
    Logs one INFO line per API request:

        method path status duration_ms user_id request_id

    Rules:
    - Logs metadata only — never the request body or response body.
    - Skips admin (/admin/) and static/media (/static/, /media/) paths.
    - Records user_id (None for anonymous) rather than email or tokens.
"""

import logging
import time
import uuid

logger = logging.getLogger("mockii.api")

# Paths that don't need per-request API logging (admin UI, static assets).
_SKIP_PREFIXES = ("/admin/", "/static/", "/media/")


class RequestIDMiddleware:
    """
    Attach a unique request ID to every inbound request.

    Resolution order:
      1. X-Request-ID header from the caller (allows external correlation).
      2. Fresh UUID4 generated by this middleware.

    The resolved ID is:
      - Stored on request.request_id for use by views and the exception handler.
      - Echoed in the X-Request-ID response header.
    """

    def __init__(self, get_response):
        self.get_response = get_response

    def __call__(self, request):
        request_id = request.headers.get("X-Request-Id") or str(uuid.uuid4())
        request.request_id = request_id

        response = self.get_response(request)
        response["X-Request-ID"] = request_id
        return response


class APILoggingMiddleware:
    """
    Log one INFO line per API request.

    Logged fields (no secrets, no bodies):
        method       HTTP verb
        path         request path
        status       HTTP status code of the response
        duration_ms  wall-clock time in milliseconds
        user_id      authenticated user PK, or None for anonymous
        request_id   value from RequestIDMiddleware (or None if not installed)
    """

    def __init__(self, get_response):
        self.get_response = get_response

    def __call__(self, request):
        # Skip admin UI and asset paths — they generate noise without value.
        if request.path.startswith(_SKIP_PREFIXES):
            return self.get_response(request)

        start = time.monotonic()
        response = self.get_response(request)
        duration_ms = (time.monotonic() - start) * 1000

        user = getattr(request, "user", None)
        user_id = user.id if (user and user.is_authenticated) else None

        logger.info(
            "API request: method=%s path=%s status=%s "
            "duration_ms=%.1f user_id=%s request_id=%s",
            request.method,
            request.path,
            response.status_code,
            duration_ms,
            user_id,
            getattr(request, "request_id", None),
        )

        return response
